// Spoilers

function ImageSpoiler00() {
    let details = document.getElementById("SpoileredImage00");
    let summary = document.getElementById("Spoiler00");
    details.addEventListener("toggle", function() {
        if (details.open) {
            summary.textContent = "Hide spoilered image";
        } else {
            summary.textContent = "Show spoilered image";
        }
    });
    return 0;
}

